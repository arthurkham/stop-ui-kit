/**
 * Builds every token artifact from the W3C DTCG sources in `tokens/`:
 *
 * - dist/tokens.css          CSS custom properties and themes (plain CSS)
 * - dist/components.css      Component tone bindings with token fallbacks
 * - dist/tailwind.css        Tailwind preset for applications (`bg-sui-primary`, ...)
 * - dist/tailwind-theme.css  Tailwind theme used to build the kit itself
 * - dist/index.js / .d.ts    Typed token references for JavaScript
 *
 * Themes are read from `tokens/$themes.json` (Tokens Studio format), and every theme is
 * checked against the contrast rules in `contrast.json`; the build fails on violations.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import StyleDictionary from 'style-dictionary';
import type { TransformedToken } from 'style-dictionary/types';

const packageRoot = join(import.meta.dirname, '..');
const tokensDir = join(packageRoot, 'tokens');

const HEADER = '/* Generated by @stop-ui/tokens from tokens/*.json. Do not edit. */\n';
const ALIAS = /^\{([^}]+)\}$/;

type TokenSetStatus = 'source' | 'enabled' | 'disabled';

export interface ThemeDefinition {
  id: string;
  name: string;
  selectedTokenSets: Record<string, TokenSetStatus>;
}

export interface ContrastRule {
  foreground: string;
  background: string[];
  min: number;
  reason: string;
}

export interface ResolvedTheme {
  id: string;
  /** Tokens shared by every theme (primitives, scale). */
  foundation: TransformedToken[];
  /** Theme-specific semantic tokens. */
  semantic: TransformedToken[];
  /** Component tokens. Optional at runtime: emitted as fallbacks, never declared. */
  component: TransformedToken[];
}

export interface ComponentMix {
  soft: number;
  'soft-hover': number;
  border: number;
}

export interface ComponentContrastRule {
  foreground: string;
  background: string;
  min: number;
  reason: string;
}

/**
 * How a component group in `tokens/components/*.json` is compiled, from
 * `$extensions["dev.stop-ui"]`:
 * - `tones`: color tones (e.g. button) bound to `--sui-tone*` per `[data-tone]`.
 * - `properties`: named tokens (e.g. input) bound to `--sui-<component>--<name>` on host elements.
 */
export type ComponentConfig =
  | { kind: 'tones'; mix: ComponentMix }
  | { kind: 'properties'; hosts: string[]; contrast: ComponentContrastRule[] };

interface DimensionValue {
  value: number;
  unit: string;
}

interface ColorValue {
  colorSpace: string;
  components: number[];
  alpha?: number;
  hex?: string;
}

const readJson = (path: string): unknown => JSON.parse(readFileSync(path, 'utf8'));

