/** `color.green.950` → `--sui-green-950`, `radius.md` → `--sui-radius-md`, `surface` → `--sui-surface`. */
export function cssVariableName(path: readonly string[]): string {
  const [group, ...rest] = path;
  const segments = group === 'color' ? rest : path;
  return `--sui-${segments.join('-')}`;
}

function toHex(color: ColorValue): string {
  if (color.hex) {
    return color.hex.toLowerCase();
  }
  if (color.colorSpace !== 'srgb') {
    throw new Error(`Only srgb colors without "hex" are supported, got ${color.colorSpace}.`);
  }
  return `#${color.components
    .map((component) =>
      Math.round(component * 255)
        .toString(16)
        .padStart(2, '0'),
    )
    .join('')}`;
}

function originalValue(token: TransformedToken): unknown {
  return (token.original as { $value?: unknown }).$value;
}

/** CSS value of a token. Aliases stay references, so themes remain overridable at runtime. */
export function cssValue(token: TransformedToken): string {
  const original = originalValue(token);
  if (typeof original === 'string') {
    const alias = ALIAS.exec(original);
    if (alias?.[1]) {
      return `var(${cssVariableName(alias[1].split('.'))})`;
    }
  }

  const value = token.$value as unknown;
  switch (token.$type) {
    case 'color':
      return toHex(value as ColorValue);
    case 'dimension': {
      const { value: amount, unit } = value as DimensionValue;
      // Every rem token except the scale itself follows `--sui-rem`.
      const isScale = token.path.length === 1 && token.path[0] === 'rem';
      return unit === 'rem' && !isScale ? `calc(var(--sui-rem) * ${amount})` : `${amount}${unit}`;
    }
    case 'duration': {
      const { value: amount, unit } = value as DimensionValue;
      return `${amount}${unit}`;
    }
    case 'cubicBezier':
      return `cubic-bezier(${(value as number[]).join(', ')})`;
    case 'number':
    case 'fontWeight':
      return String(value);
    default:
      throw new Error(
        `Unsupported token type "${String(token.$type)}" at ${token.path.join('.')}.`,
      );
  }
}

