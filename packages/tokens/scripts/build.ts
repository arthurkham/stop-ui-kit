function relativeLuminance(hex: string): number {
  const channels = [1, 3, 5].map((index) => {
    const channel = Number.parseInt(hex.slice(index, index + 2), 16) / 255;
    return channel <= 0.04045 ? channel / 12.92 : ((channel + 0.055) / 1.055) ** 2.4;
  });
  const [r = 0, g = 0, b = 0] = channels;
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

/** WCAG 2.x contrast ratio between two sRGB hex colors. */
export function contrastRatio(a: string, b: string): number {
  const [lighter, darker] = [relativeLuminance(a), relativeLuminance(b)].sort((x, y) => y - x);
  return ((lighter ?? 0) + 0.05) / ((darker ?? 0) + 0.05);
}

export interface ContrastResult {
  theme: string;
  foreground: string;
  background: string;
  ratio: number;
  min: number;
  reason: string;
  passed: boolean;
}

export function checkContrast(themes: ResolvedTheme[], rules: ContrastRule[]): ContrastResult[] {
  return themes.flatMap((theme) => {
    const colors = new Map(
      [...theme.semantic, ...theme.component]
        .filter((token) => token.$type === 'color')
        .map((token) => [token.path.join('.'), toHex(token.$value as ColorValue)]),
    );
    const colorOf = (name: string): string => {
      const color = colors.get(name);
      if (!color) {
        throw new Error(`contrast.json references unknown token "${name}" (theme "${theme.id}").`);
      }
      return color;
    };

    return rules.flatMap((rule) =>
      rule.background.map((background) => {
        const ratio = contrastRatio(colorOf(rule.foreground), colorOf(background));
        return {
          theme: theme.id,
          foreground: rule.foreground,
          background,
          ratio,
          min: rule.min,
          reason: rule.reason,
          passed: ratio >= rule.min,
        };
      }),
    );
  });
}

/** Composites `color` at `percent` opacity over `background`, like `color-mix(in srgb, …, transparent)`. */
export function mixOver(color: string, percent: number, background: string): string {
  const channel = (hex: string, index: number) => Number.parseInt(hex.slice(index, index + 2), 16);
  const amount = percent / 100;
  return `#${[1, 3, 5]
    .map((index) =>
      Math.round(channel(color, index) * amount + channel(background, index) * (1 - amount))
        .toString(16)
        .padStart(2, '0'),
    )
    .join('')}`;
}

/** Tone names of a component group, e.g. `button` → `primary`, `neutral`, `danger`. */
export function componentTones(theme: ResolvedTheme, component: string): string[] {
  return theme.component
    .filter((token) => token.path[0] === component && token.path.length === 2)
    .map((token) => token.path[1] ?? '')
    .filter((name) => !/-(hover|fg|text)$/.test(name));
}

export function readComponentConfig(component: string): ComponentConfig {
  const source = readJson(join(tokensDir, 'components', `${component}.json`)) as Record<
    string,
    {
      $extensions?: {
        'dev.stop-ui'?: {
          kind?: string;
          mix?: ComponentMix;
          hosts?: string[];
          contrast?: ComponentContrastRule[];
        };
      };
    }
  >;
  const config = source[component]?.$extensions?.['dev.stop-ui'];
  if (config?.kind === 'properties' && config.hosts?.length) {
    return { kind: 'properties', hosts: config.hosts, contrast: config.contrast ?? [] };
  }
  if (config?.mix) {
    return { kind: 'tones', mix: config.mix };
  }
  throw new Error(
    `tokens/components/${component}.json must define $extensions["dev.stop-ui"] with either ` +
      '"mix" (tones) or "kind": "properties" and "hosts".',
  );
}

/**
 * Checks every tone of a component in every shape it is used in: text on the solid color and its
 * hover state, and tone-colored text on the surface and on the derived soft tints.
 */
export function checkComponentContrast(
  themes: ResolvedTheme[],
  component: string,
  config: ComponentConfig,
): ContrastResult[] {
  if (config.kind === 'properties') {
    return checkComponentProperties(themes, component, config.contrast);
  }
  const { mix } = config;
  return themes.flatMap((theme) => {
    const colors = new Map(
      [...theme.semantic, ...theme.component].map((token) => [
        token.path.join('.'),
        toHex(token.$value as ColorValue),
      ]),
    );
    const get = (name: string): string => {
      const color = colors.get(name);
      if (!color) throw new Error(`Missing token "${name}" in theme "${theme.id}".`);
      return color;
    };
    const surface = get('surface');

    return componentTones(theme, component).flatMap((tone) => {
      const key = (role: string) => `${component}.${tone}${role ? `-${role}` : ''}`;
      const color = get(key(''));
      const text = get(key('text'));
      const pairs: [string, string, string, string][] = [
        [key('fg'), get(key('fg')), key(''), color],
        [key('fg'), get(key('fg')), key('hover'), get(key('hover'))],
        [key('text'), text, 'surface', surface],
        [key('text'), text, `${key('')} ${mix.soft}% tint`, mixOver(color, mix.soft, surface)],
        [
          key('text'),
          text,
          `${key('')} ${mix['soft-hover']}% tint`,
          mixOver(color, mix['soft-hover'], surface),
        ],
      ];
      return pairs.map(([foreground, fg, background, bg]) => {
        const ratio = contrastRatio(fg, bg);
        return {
          theme: theme.id,
          foreground,
          background,
          ratio,
          min: 4.5,
          reason: 'Button text in every shape (WCAG 1.4.3).',
          passed: ratio >= 4.5,
        };
      });
    });
  });
}

/** Checks the contrast rules declared by a `properties` component, e.g. placeholder on input background. */
function checkComponentProperties(
  themes: ResolvedTheme[],
  component: string,
  rules: ComponentContrastRule[],
): ContrastResult[] {
  return themes.flatMap((theme) => {
    const colors = new Map(
      [...theme.semantic, ...theme.component].map((token) => [
        token.path.join('.'),
        toHex(token.$value as ColorValue),
      ]),
    );
    // Names are local to the component first (`placeholder` → `input.placeholder`), then semantic.
    const get = (name: string): string => {
      const color = colors.get(`${component}.${name}`) ?? colors.get(name);
      if (!color) throw new Error(`Unknown token "${name}" in ${component} contrast rules.`);
      return color;
    };
    return rules.map((rule) => {
      const ratio = contrastRatio(get(rule.foreground), get(rule.background));
      return {
        theme: theme.id,
        foreground: `${component}.${rule.foreground}`,
        background: `${component}.${rule.background}`,
        ratio,
        min: rule.min,
        reason: rule.reason,
        passed: ratio >= rule.min,
      };
    });
  });
}

