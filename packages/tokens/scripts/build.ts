const declarations = (tokens: TransformedToken[], indent: string): string =>
  tokens.map((token) => `${indent}${cssVariableName(token.path)}: ${cssValue(token)};`).join('\n');

export function formatTokensCss(themes: ResolvedTheme[]): string {
  const [defaultTheme] = themes;
  const dark = themes.find((theme) => theme.id === 'dark');
  if (!defaultTheme || !dark) {
    throw new Error('$themes.json must define a default (first) theme and a "dark" theme.');
  }
  const others = themes.filter((theme) => theme !== defaultTheme && theme !== dark);

  return `${HEADER}
/*
 * Themes are applied with \`data-sui-theme="${themes.map((t) => t.id).join('" | "')}" | "system"\`
 * on any element. Custom properties inherit, so themes can be nested.
 */
@layer theme {
  :root,
  :host {
${declarations(defaultTheme.foundation, '    ')}
  }

  /* "${defaultTheme.id}" is the default; "system" starts from it so it is correct inside any subtree. */
  :root,
  :host,
  [data-sui-theme='${defaultTheme.id}'],
  [data-sui-theme='system'] {
${declarations(defaultTheme.semantic, '    ')}
  }

  [data-sui-theme='${defaultTheme.id}'] {
    color-scheme: light;
  }

  [data-sui-theme='dark'] {
    color-scheme: dark;
${declarations(dark.semantic, '    ')}
  }
${others
  .map(
    (theme) => `
  [data-sui-theme='${theme.id}'] {
${declarations(theme.semantic, '    ')}
  }
`,
  )
  .join('')}
  [data-sui-theme='system'] {
    color-scheme: light dark;
  }

  @media (prefers-color-scheme: dark) {
    [data-sui-theme='system'] {
      color-scheme: dark;
${declarations(dark.semantic, '      ')}
    }
  }
}
`;
}

const keysOf = (tokens: TransformedToken[], group: string): string[] =>
  tokens.filter((token) => token.path[0] === group).map((token) => token.path.slice(1).join('-'));

export function formatTailwindTheme(theme: ResolvedTheme): string {
  const { foundation, semantic } = theme;
  const lines = [
    // Start from an empty theme: the kit relies only on values it owns.
    '--*: initial;',
    '--spacing: var(--sui-spacing);',
    ...keysOf(foundation, 'text').flatMap((key) => [
      `--text-${key}: var(--sui-text-${key});`,
      `--text-${key}--line-height: var(--sui-leading-${key});`,
    ]),
    ...keysOf(foundation, 'radius').map((key) => `--radius-${key}: var(--sui-radius-${key});`),
    ...keysOf(foundation, 'font-weight').map(
      (key) => `--font-weight-${key}: var(--sui-font-weight-${key});`,
    ),
    '--default-transition-duration: var(--sui-duration-fast);',
    '--default-transition-timing-function: var(--sui-easing-standard);',
    '--animate-spin: sui-spin 1s linear infinite;',
    ...semantic.map((token) => {
      const name = token.path.join('-');
      return `--color-${name}: var(--sui-${name});`;
    }),
  ];

  return `${HEADER}
/*
 * Tailwind theme for building the kit (Tailwind runs with \`prefix(sui)\`). Every value points
 * at a token, so overriding a token restyles the kit at runtime.
 */
@theme inline {
${lines.map((line) => `  ${line}`).join('\n')}

  @keyframes sui-spin {
    to {
      transform: rotate(360deg);
    }
  }
}
`;
}

export function formatTailwindPreset(theme: ResolvedTheme): string {
  const { foundation, semantic } = theme;
  const lines = [
    ...semantic.map((token) => {
      const name = token.path.join('-');
      return `--color-sui-${name}: var(--sui-${name});`;
    }),
    ...keysOf(foundation, 'radius').map((key) => `--radius-sui-${key}: var(--sui-radius-${key});`),
    ...keysOf(foundation, 'text').flatMap((key) => [
      `--text-sui-${key}: var(--sui-text-${key});`,
      `--text-sui-${key}--line-height: var(--sui-leading-${key});`,
    ]),
  ];

  return `${HEADER}
/*
 * Tailwind preset that lets an application use Stop UI tokens in its own markup:
 * \`bg-sui-primary\`, \`text-sui-fg\`, \`border-sui-border\`, \`rounded-sui-md\`, \`text-sui-sm\`.
 *
 *   @import 'tailwindcss';
 *   @import '@stop-ui/tokens/tokens.css';
 *   @import '@stop-ui/tokens/tailwind.css';
 */
@theme inline {
${lines.map((line) => `  ${line}`).join('\n')}
}
`;
}

const camelCase = (value: string): string =>
  value.replace(/-([a-z0-9])/g, (_, char: string) => char.toUpperCase());

export function buildJsModule(theme: ResolvedTheme): { js: string; dts: string } {
  const reference = (token: TransformedToken) => `var(${cssVariableName(token.path)})`;
  const group = (name: string) =>
    Object.fromEntries(
      theme.foundation
        .filter((token) => token.path[0] === name)
        .map((token) => [token.path.slice(1).join('-'), reference(token)]),
    );

  const tokens = {
    color: Object.fromEntries(
      theme.semantic.map((token) => [camelCase(token.path.join('-')), reference(token)]),
    ),
    rem: 'var(--sui-rem)',
    spacing: 'var(--sui-spacing)',
    radius: group('radius'),
    text: group('text'),
    leading: group('leading'),
    fontWeight: group('font-weight'),
    duration: group('duration'),
    easing: group('easing'),
  };

  const palette: Record<string, Record<string, string> | string> = {};
  for (const token of theme.foundation.filter((t) => t.path[0] === 'color')) {
    const [, family, step] = token.path;
    const hex = toHex(token.$value as ColorValue);
    if (!family) continue;
    if (step === undefined) {
      palette[family] = hex;
    } else {
      const scale = (palette[family] ??= {}) as Record<string, string>;
      scale[step] = hex;
    }
  }

  const tokensJson = JSON.stringify(tokens, null, 2);
  const paletteJson = JSON.stringify(palette, null, 2);

  const js = `${HEADER}
/** Theme-aware references to Stop UI tokens, e.g. \`tokens.color.primary\` → \`'var(--sui-primary)'\`. */
export const tokens = ${tokensJson};

/** Raw palette values. Prefer \`tokens\`, which follow the active theme. */
export const palette = ${paletteJson};
`;

  const dts = `${HEADER}
/** Theme-aware references to Stop UI tokens, e.g. \`tokens.color.primary\` → \`'var(--sui-primary)'\`. */
export declare const tokens: ${tokensJson};

/** Raw palette values. Prefer \`tokens\`, which follow the active theme. */
export declare const palette: ${paletteJson};

export type SemanticColor = keyof (typeof tokens)['color'];
export type Theme = ${['system', 'dark', theme.id].map((id) => `'${id}'`).join(' | ')};
`;

  return { js, dts };
}

// ---------------------------------------------------------------------------
// Build
// ---------------------------------------------------------------------------

export async function buildTokens(outDir = join(packageRoot, 'dist')): Promise<ContrastResult[]> {
  const themes = await loadThemes();
  const [defaultTheme] = themes;
  if (!defaultTheme) {
    throw new Error('$themes.json defines no themes.');
  }

  const results = checkContrast(
    themes,
    readJson(join(packageRoot, 'contrast.json')) as ContrastRule[],
  );
  const failures = results.filter((result) => !result.passed);
  if (failures.length > 0) {
    const list = failures
      .map(
        (f) =>
          `  [${f.theme}] ${f.foreground} on ${f.background}: ${f.ratio.toFixed(2)}:1 (needs ${f.min}:1) — ${f.reason}`,
      )
      .join('\n');
    throw new Error(`Contrast check failed:\n${list}`);
  }

  const { js, dts } = buildJsModule(defaultTheme);
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, 'tokens.css'), formatTokensCss(themes));
  writeFileSync(join(outDir, 'tailwind-theme.css'), formatTailwindTheme(defaultTheme));
  writeFileSync(join(outDir, 'tailwind.css'), formatTailwindPreset(defaultTheme));
  writeFileSync(join(outDir, 'index.js'), js);
  writeFileSync(join(outDir, 'index.d.ts'), dts);

  return results;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const results = await buildTokens();
  const lowest = [...results].sort((a, b) => a.ratio - a.min - (b.ratio - b.min))[0];
  console.log(`@stop-ui/tokens: built, ${results.length} contrast pairs passed.`);
  if (lowest) {
    console.log(
      `  Tightest pair: [${lowest.theme}] ${lowest.foreground} on ${lowest.background} ${lowest.ratio.toFixed(2)}:1 (min ${lowest.min}:1)`,
    );
  }
}
