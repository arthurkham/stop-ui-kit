/**
 * Builds every token artifact from the W3C DTCG sources in `tokens/`:
 *
 * - dist/tokens.css          CSS custom properties and themes (plain CSS)
 * - dist/tailwind.css        Tailwind preset for applications (`bg-sui-primary`, ...)
 * - dist/tailwind-theme.css  Tailwind theme used to build the kit itself
 * - dist/index.js / .d.ts    Typed token references for JavaScript
 *
 * Themes are read from `tokens/$themes.json` (Tokens Studio format), and every theme is
 * checked against the contrast rules in `contrast.json`; the build fails on violations.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import StyleDictionary from 'style-dictionary';
import type { TransformedToken } from 'style-dictionary/types';

const packageRoot = join(import.meta.dirname, '..');
const tokensDir = join(packageRoot, 'tokens');

const HEADER = '/* Generated by @stop-ui/tokens from tokens/*.json. Do not edit. */\n';
const ALIAS = /^\{([^}]+)\}$/;

type TokenSetStatus = 'source' | 'enabled' | 'disabled';

export interface ThemeDefinition {
  id: string;
  name: string;
  selectedTokenSets: Record<string, TokenSetStatus>;
}

export interface ContrastRule {
  foreground: string;
  background: string[];
  min: number;
  reason: string;
}

export interface ResolvedTheme {
  id: string;
  /** Tokens shared by every theme (primitives, scale). */
  foundation: TransformedToken[];
  /** Theme-specific semantic tokens. */
  semantic: TransformedToken[];
}

interface DimensionValue {
  value: number;
  unit: string;
}

interface ColorValue {
  colorSpace: string;
  components: number[];
  alpha?: number;
  hex?: string;
}

const readJson = (path: string): unknown => JSON.parse(readFileSync(path, 'utf8'));

// ---------------------------------------------------------------------------
// Naming and values
// ---------------------------------------------------------------------------

/** `color.green.950` → `--sui-green-950`, `radius.md` → `--sui-radius-md`, `surface` → `--sui-surface`. */
export function cssVariableName(path: readonly string[]): string {
  const [group, ...rest] = path;
  const segments = group === 'color' ? rest : path;
  return `--sui-${segments.join('-')}`;
}

function toHex(color: ColorValue): string {
  if (color.hex) {
    return color.hex.toLowerCase();
  }
  if (color.colorSpace !== 'srgb') {
    throw new Error(`Only srgb colors without "hex" are supported, got ${color.colorSpace}.`);
  }
  return `#${color.components
    .map((component) =>
      Math.round(component * 255)
        .toString(16)
        .padStart(2, '0'),
    )
    .join('')}`;
}

function originalValue(token: TransformedToken): unknown {
  return (token.original as { $value?: unknown }).$value;
}

/** CSS value of a token. Aliases stay references, so themes remain overridable at runtime. */
export function cssValue(token: TransformedToken): string {
  const original = originalValue(token);
  if (typeof original === 'string') {
    const alias = ALIAS.exec(original);
    if (alias?.[1]) {
      return `var(${cssVariableName(alias[1].split('.'))})`;
    }
  }

  const value = token.$value as unknown;
  switch (token.$type) {
    case 'color':
      return toHex(value as ColorValue);
    case 'dimension': {
      const { value: amount, unit } = value as DimensionValue;
      // Every rem token except the scale itself follows `--sui-rem`.
      const isScale = token.path.length === 1 && token.path[0] === 'rem';
      return unit === 'rem' && !isScale ? `calc(var(--sui-rem) * ${amount})` : `${amount}${unit}`;
    }
    case 'duration': {
      const { value: amount, unit } = value as DimensionValue;
      return `${amount}${unit}`;
    }
    case 'cubicBezier':
      return `cubic-bezier(${(value as number[]).join(', ')})`;
    case 'number':
    case 'fontWeight':
      return String(value);
    default:
      throw new Error(
        `Unsupported token type "${String(token.$type)}" at ${token.path.join('.')}.`,
      );
  }
}

// ---------------------------------------------------------------------------
// Loading
// ---------------------------------------------------------------------------

export async function loadThemes(): Promise<ResolvedTheme[]> {
  const definitions = readJson(join(tokensDir, '$themes.json')) as ThemeDefinition[];

  return Promise.all(
    definitions.map(async (definition) => {
      const sets = Object.entries(definition.selectedTokenSets).filter(
        ([, status]) => status !== 'disabled',
      );
      const enabledFiles = new Set(
        sets.filter(([, status]) => status === 'enabled').map(([set]) => `tokens/${set}.json`),
      );

      const dictionary = new StyleDictionary({
        source: sets.map(([set]) => join(tokensDir, `${set}.json`)),
        usesDtcg: true,
        log: { verbosity: 'silent', warnings: 'disabled' },
        platforms: { css: { transforms: [] } },
      });
      const { allTokens } = await dictionary.getPlatformTokens('css');

      const isEnabled = (token: TransformedToken) =>
        enabledFiles.has(relative(packageRoot, token.filePath).split('\\').join('/'));

      return {
        id: definition.id,
        foundation: allTokens.filter((token) => !isEnabled(token)),
        semantic: allTokens.filter(isEnabled),
      };
    }),
  );
}

// ---------------------------------------------------------------------------
// Contrast
// ---------------------------------------------------------------------------

function relativeLuminance(hex: string): number {
  const channels = [1, 3, 5].map((index) => {
    const channel = Number.parseInt(hex.slice(index, index + 2), 16) / 255;
    return channel <= 0.04045 ? channel / 12.92 : ((channel + 0.055) / 1.055) ** 2.4;
  });
  const [r = 0, g = 0, b = 0] = channels;
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

/** WCAG 2.x contrast ratio between two sRGB hex colors. */
export function contrastRatio(a: string, b: string): number {
  const [lighter, darker] = [relativeLuminance(a), relativeLuminance(b)].sort((x, y) => y - x);
  return ((lighter ?? 0) + 0.05) / ((darker ?? 0) + 0.05);
}

export interface ContrastResult {
  theme: string;
  foreground: string;
  background: string;
  ratio: number;
  min: number;
  reason: string;
  passed: boolean;
}

export function checkContrast(themes: ResolvedTheme[], rules: ContrastRule[]): ContrastResult[] {
  return themes.flatMap((theme) => {
    const colors = new Map(
      theme.semantic
        .filter((token) => token.$type === 'color')
        .map((token) => [token.path.join('.'), toHex(token.$value as ColorValue)]),
    );
    const colorOf = (name: string): string => {
      const color = colors.get(name);
      if (!color) {
        throw new Error(`contrast.json references unknown token "${name}" (theme "${theme.id}").`);
      }
      return color;
    };

    return rules.flatMap((rule) =>
      rule.background.map((background) => {
        const ratio = contrastRatio(colorOf(rule.foreground), colorOf(background));
        return {
          theme: theme.id,
          foreground: rule.foreground,
          background,
          ratio,
          min: rule.min,
          reason: rule.reason,
          passed: ratio >= rule.min,
        };
      }),
    );
  });
}

